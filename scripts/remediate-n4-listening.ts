export function remediateN4Listening(): void {
  console.log('[Stage 3] Remediating Listening Turns Generation & Audio Alignment...');

  for (let i = 1; i <= 36; i++) {
    const packId = `n4.l${String(i).padStart(2, '0')}`;
    const filePath = path.join(PACKS_DIR, `${packId}.json`);
    if (!fs.existsSync(filePath)) continue;

    const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    let modified = false;

    // 1. L01-L10: Populate listening.turns and translationMy
    if (i >= 1 && i <= 10 && L01_L10_TURNS[packId]) {
      const config = L01_L10_TURNS[packId];
      data.listening.speakers = config.speakers;
      data.listening.turns = config.turns.map(t => ({
        speaker: t.speaker,
        ja: t.ja,
        kana: t.kana,
        en: t.en,
        my: t.my,
        myanmar: t.my,
        translationMy: t.my,
      }));
      data.listening.translationMy = config.translationMy;
      modified = true;
      console.log(`  ✓ Generated ${data.listening.turns.length} turns and translationMy for ${packId}`);
    }

    // 2. L11-L23: Fix kana fields, populate en, my, myanmar, translationMy
    if (i >= 11 && i <= 23 && data.listening?.turns) {
      const kanas = L11_L23_KANA_MAP[packId] || [];
      const burmese = L11_L23_BURMESE_MAP[packId] || [];

      // Extract English translation lines
      const trans = typeof data.listening.translation === 'string'
        ? data.listening.translation
        : (data.listening.translation?.en || '');
      const enLines = trans.split('\n')
        .map((l: string) => l.trim())
        .filter((l: string) => l.length > 0)
        .map((l: string) => {
          const idx = l.indexOf(': ');
          return idx !== -1 ? l.slice(idx + 2).trim() : l;
        });

      data.listening.turns.forEach((turn: any, idx: number) => {
        if (kanas[idx]) {
          turn.kana = kanas[idx];
        }
        if (!turn.en && enLines[idx]) {
          turn.en = enLines[idx];
        }
        if (burmese[idx]) {
          turn.my = burmese[idx];
          turn.myanmar = burmese[idx];
          turn.translationMy = burmese[idx];
        }
      });

      // Update full listening.translationMy
      if (burmese.length > 0) {
        data.listening.translationMy = data.listening.turns
          .map((t: any) => `${t.speaker}- ${t.my}`)
          .join('\n');
      }

      modified = true;
      console.log(`  ✓ Fixed phonetics and Burmese localized turns for ${packId}`);
    }

    // 3. L24-L36: Replace English placeholders in turns[].my with Burmese
    if (i >= 24 && i <= 36 && data.listening?.turns) {
      // Localize turns for L24-L36
      data.listening.turns.forEach((t: any) => {
        // If English placeholder is detected in my
        if (t.my && /^[A-Za-z]/.test(t.my.trim())) {
          // Provide natural Burmese translation based on ja text
          t.my = localizeTurnJaToBurmese(t.ja, t.en);
          t.myanmar = t.my;
          t.translationMy = t.my;
        }
      });

      data.listening.translationMy = data.listening.turns
        .map((t: any) => `${t.speaker}- ${t.my}`)
        .join('\n');

      modified = true;
      console.log(`  ✓ Localized turns and translationMy for ${packId}`);
    }

    if (modified) {
      fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n', 'utf8');
    }
  }

  console.log('[Stage 3] Completed successfully!\n');
}

