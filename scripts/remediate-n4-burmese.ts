      mistakeHint = 'သတိပြုရန်- စကားပြောတွင် ら ကို ဖြုတ်၍ပြောလေ့ရှိသော်လည်း စာမေးပွဲတွင် られる ပုံစံကိုသာ မှန်ကန်စွာ သုံးရပါမည်။';
